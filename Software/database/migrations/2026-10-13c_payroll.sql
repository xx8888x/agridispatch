-- 2026-10-13 出勤補登／修正與月結算：建 attendance_corrections、payroll_months、payroll_slips 三張表
-- 規則見後端 PayrollService；科技後台 TechBackend/payroll.html
-- 可重複執行：表已存在就略過
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM all_tables
     WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AND table_name = 'ATTENDANCE_CORRECTIONS';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE attendance_corrections (
                id                 NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
                clock_in_id        NUMBER(19)          NOT NULL,
                worker_id          VARCHAR2(32 CHAR)   NOT NULL,
                work_date          DATE                NOT NULL,
                action             VARCHAR2(10 CHAR)   NOT NULL,
                before_clock_in    TIMESTAMP,
                before_clock_out   TIMESTAMP,
                after_clock_in     TIMESTAMP           NOT NULL,
                after_clock_out    TIMESTAMP           NOT NULL,
                reason             VARCHAR2(200 CHAR)  NOT NULL,
                operator           VARCHAR2(64 CHAR)   NOT NULL,
                created_at         TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT pk_attendance_corrections PRIMARY KEY (id),
                CONSTRAINT fk_att_corr_clock_in FOREIGN KEY (clock_in_id) REFERENCES clock_ins(id),
                CONSTRAINT fk_att_corr_worker FOREIGN KEY (worker_id) REFERENCES workers(id),
                CONSTRAINT chk_att_corr_action CHECK (action IN ('create', 'update'))
            )]';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_att_corr_clock_in ON attendance_corrections (clock_in_id)';
        EXECUTE IMMEDIATE q'[COMMENT ON TABLE attendance_corrections IS '出勤補登／修正紀錄：科技後台每次補登或修正 clock_ins 留改前、改後、原因與操作人；不可修改刪除']';
        EXECUTE IMMEDIATE q'[COMMENT ON COLUMN attendance_corrections.action IS 'create 補登 / update 修正']';
    END IF;

    SELECT COUNT(*) INTO n FROM all_tables
     WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AND table_name = 'PAYROLL_MONTHS';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE payroll_months (
                pay_month          VARCHAR2(7 CHAR)    NOT NULL,
                status             VARCHAR2(10 CHAR)   NOT NULL,
                settled_at         TIMESTAMP,
                settled_by         VARCHAR2(64 CHAR),
                worker_count       NUMBER(10),
                total_net          NUMBER(19),
                reopened_at        TIMESTAMP,
                reopened_by        VARCHAR2(64 CHAR),
                reopen_reason      VARCHAR2(200 CHAR),
                CONSTRAINT pk_payroll_months PRIMARY KEY (pay_month),
                CONSTRAINT chk_payroll_months_status CHECK (status IN ('settled', 'reopened'))
            )]';
        EXECUTE IMMEDIATE q'[COMMENT ON TABLE payroll_months IS '月結算狀態：只有結算過的月份才有資料列；settled 時該月出勤鎖定']';
        EXECUTE IMMEDIATE q'[COMMENT ON COLUMN payroll_months.pay_month IS 'YYYY-MM']';
        EXECUTE IMMEDIATE q'[COMMENT ON COLUMN payroll_months.status IS 'settled 已結算 / reopened 已重新開放（快照已刪除）']';
    END IF;

    SELECT COUNT(*) INTO n FROM all_tables
     WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AND table_name = 'PAYROLL_SLIPS';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE payroll_slips (
                id                  VARCHAR2(40 CHAR)   NOT NULL,
                pay_month           VARCHAR2(7 CHAR)    NOT NULL,
                worker_id           VARCHAR2(32 CHAR)   NOT NULL,
                worker_name         VARCHAR2(100 CHAR),
                tier                VARCHAR2(30 CHAR),
                work_days           NUMBER(3)           DEFAULT 0 NOT NULL,
                worked_hours        NUMBER(8,2)         DEFAULT 0 NOT NULL,
                overtime_hours      NUMBER(8,2)         DEFAULT 0 NOT NULL,
                base_salary         NUMBER(10)          DEFAULT 0 NOT NULL,
                agri_subsidy        NUMBER(10)          DEFAULT 0 NOT NULL,
                transport_allowance NUMBER(10)          DEFAULT 0 NOT NULL,
                overtime_pay        NUMBER(10)          DEFAULT 0 NOT NULL,
                labor_insurance     NUMBER(10)          DEFAULT 0 NOT NULL,
                health_insurance    NUMBER(10)          DEFAULT 0 NOT NULL,
                gross_pay           NUMBER(10)          DEFAULT 0 NOT NULL,
                total_deductions    NUMBER(10)          DEFAULT 0 NOT NULL,
                net_pay             NUMBER(10)          DEFAULT 0 NOT NULL,
                created_at          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT pk_payroll_slips PRIMARY KEY (id),
                CONSTRAINT fk_payroll_slips_month FOREIGN KEY (pay_month) REFERENCES payroll_months(pay_month),
                CONSTRAINT fk_payroll_slips_worker FOREIGN KEY (worker_id) REFERENCES workers(id),
                CONSTRAINT uq_payroll_slips_month_worker UNIQUE (pay_month, worker_id)
            )]';
        EXECUTE IMMEDIATE q'[COMMENT ON TABLE payroll_slips IS '月結算薪資單快照（PS-YYYYMM-工號）；重新開放該月時刪除。勞健保自付額為概估']';
    END IF;
END;
