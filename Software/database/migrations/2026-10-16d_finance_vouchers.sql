-- 2026-10-16 財務報表的實際收支：建 finance_vouchers（傳票表頭）、finance_voucher_lines（傳票明細）
-- 規則見後端 FinanceVoucherService／FinanceReportService；科技後台 TechBackend/admin.html「財報」分頁
-- 可重複執行：表已存在就略過
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM all_tables
     WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AND table_name = 'FINANCE_VOUCHERS';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE finance_vouchers (
                id            NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
                voucher_no    VARCHAR2(16 CHAR)   NOT NULL,
                voucher_date  DATE                NOT NULL,
                memo          VARCHAR2(200 CHAR)  NOT NULL,
                status        VARCHAR2(10 CHAR)   DEFAULT 'active' NOT NULL,
                created_by    VARCHAR2(64 CHAR)   NOT NULL,
                created_at    TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
                void_reason   VARCHAR2(200 CHAR),
                voided_by     VARCHAR2(64 CHAR),
                voided_at     TIMESTAMP,
                CONSTRAINT pk_finance_vouchers PRIMARY KEY (id),
                CONSTRAINT uq_finance_vouchers_no UNIQUE (voucher_no),
                CONSTRAINT chk_finance_vouchers_status CHECK (status IN ('active', 'void'))
            )]';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_finance_vouchers_date ON finance_vouchers (voucher_date)';
        EXECUTE IMMEDIATE q'[COMMENT ON TABLE finance_vouchers IS '傳票表頭：科技後台登錄的實際收支，借貸須平衡；不可修改，錯誤以作廢（void）處理並保留紀錄']';
    END IF;

    SELECT COUNT(*) INTO n FROM all_tables
     WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AND table_name = 'FINANCE_VOUCHER_LINES';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE finance_voucher_lines (
                id            NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
                voucher_id    NUMBER(19)          NOT NULL,
                line_no       NUMBER(3)           NOT NULL,
                account_code  VARCHAR2(8 CHAR)    NOT NULL,
                debit         NUMBER(15)          DEFAULT 0 NOT NULL,
                credit        NUMBER(15)          DEFAULT 0 NOT NULL,
                note          VARCHAR2(100 CHAR),
                CONSTRAINT pk_finance_voucher_lines PRIMARY KEY (id),
                CONSTRAINT fk_fin_lines_voucher FOREIGN KEY (voucher_id) REFERENCES finance_vouchers(id),
                CONSTRAINT chk_fin_lines_side CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0))
            )]';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_fin_lines_voucher ON finance_voucher_lines (voucher_id)';
        EXECUTE IMMEDIATE q'[COMMENT ON TABLE finance_voucher_lines IS '傳票明細：一列只有借方或貸方有金額（元）；科目代號見後端 FinanceAccounts']';
    END IF;
END;
